#!/usr/bin/env bun
/**
 * Writes helpers/phoneZones.data.ts: which time zones each phone number
 * prefix is in, from Google's libphonenumber (resources/timezones/
 * map_data.txt, Apache License 2.0) at a pinned commit. Run it to move to a
 * newer commit: `bun run data:phoneZones [commit]`.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";

const COMMIT = process.argv[2] ?? "1ae0d623301b302f828628dfc368c983e8d27141";
const SOURCE = `https://raw.githubusercontent.com/google/libphonenumber/${COMMIT}/resources/timezones/map_data.txt`;
const OUT = path.join(import.meta.dir, "helpers", "phoneZones.data.ts");

const isZone = (name: string) => {
  try {
    new Intl.DateTimeFormat("en-US", { timeZone: name });
    return true;
  } catch {
    return false;
  }
};

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE}: ${response.status}`);
const zones: string[] = [];
const index = new Map<string, number>();
const entries: string[] = [];
let dropped = 0;
for (const line of (await response.text()).split("\n")) {
  const m = /^(\d+)\|(.+)$/.exec(line.trim());
  if (!m) continue;
  const ids: number[] = [];
  for (const zone of m[2]!.split("&")) {
    if (!isZone(zone)) {
      dropped++;
      continue;
    }
    if (!index.has(zone)) {
      index.set(zone, zones.length);
      zones.push(zone);
    }
    ids.push(index.get(zone)!);
  }
  if (ids.length) entries.push(`${m[1]}:${ids.join(",")}`);
}
if (entries.length < 1000) throw new Error(`Only ${entries.length} prefixes: is ${SOURCE} the right file?`);

writeFileSync(
  OUT,
  `// Generated by src/domains/callHours/build.ts from Google's libphonenumber,
// resources/timezones/map_data.txt at ${COMMIT}
// (Apache License 2.0, see THIRD_PARTY_NOTICES.md). Do not edit by hand.

/** Every time zone a prefix can be in, referenced by index in PHONE_PREFIXES. */
export const PHONE_ZONE_NAMES: readonly string[] = ${JSON.stringify(zones)};

/** "prefix:zone,zone" entries, ";" between them: an E.164 number's longest matching prefix gives its zones. */
export const PHONE_PREFIXES = ${JSON.stringify(entries.join(";"))};
`,
);
console.log(`${entries.length} prefixes, ${zones.length} zones${dropped ? `, ${dropped} unknown zone names dropped` : ""} -> ${path.relative(process.cwd(), OUT)}`);
